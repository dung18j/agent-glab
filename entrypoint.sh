#!/usr/bin/env bash
# Container entrypoint.
#
# Projects runtime environment variables onto git config so that cloning,
# committing, pushing and reviewing work without extra setup, then runs the
# requested command.
set -euo pipefail

# --- git identity -----------------------------------------------------------
# .env sets GIT_AUTHOR_NAME / GIT_AUTHOR_EMAIL (and the committer pair). Mirror
# them into git config so tools that read user.name / user.email also work.
name="${GIT_AUTHOR_NAME:-${GIT_USER_NAME:-}}"
email="${GIT_AUTHOR_EMAIL:-${GIT_USER_EMAIL:-}}"
[ -n "${name}" ] && git config --global user.name "${name}"
[ -n "${email}" ] && git config --global user.email "${email}"

# --- GitLab credentials -----------------------------------------------------
# Scope the glab credential helper to the configured GitLab host only.
# `glab auth git-credential` answers with the GitLab token for whatever host it
# is asked about, so a catch-all helper would hand GITLAB_TOKEN to any HTTPS
# remote, for example github.com.
host="${GITLAB_HOST:-gitlab.com}"
host="${host#*://}"   # drop a scheme, if present
host="${host%%/*}"    # drop a path, if present
if [ -n "${host}" ]; then
    export GITLAB_HOST="${host}"
    git config --global "credential.https://${host}.helper" "!glab auth git-credential"

    # Also record the host and token in glab's own config file. Agent tooling
    # may run commands in a shell that does not inherit the container
    # environment, and without this glab would default back to gitlab.com and
    # find no token. Env still wins when it is present. --global avoids
    # requiring a Git repository, and -h scopes the token to the host.
    glab config set --global host "${host}" >/dev/null 2>&1 || true
    glab config set --global git_protocol https >/dev/null 2>&1 || true
    if [ -n "${GITLAB_TOKEN:-}" ]; then
        glab config set token "${GITLAB_TOKEN}" -h "${host}" >/dev/null 2>&1 || true
    fi
fi

# --- Claude Code first run ----------------------------------------------------
# run.sh starts each session with a fresh ~/.claude unless asked to persist.
# Mark onboarding as done so Claude Code does not walk through the first-run
# setup (theme picker and so on) every time. Other state is left alone.
claude_state="${CLAUDE_CONFIG_DIR:-${HOME}}/.claude.json"
if [ ! -s "${claude_state}" ]; then
    printf '{"hasCompletedOnboarding":true}\n' >"${claude_state}" 2>/dev/null || true
elif ! jq -e '.hasCompletedOnboarding == true' "${claude_state}" >/dev/null 2>&1; then
    tmp="$(mktemp "${claude_state}.XXXXXX")"
    if jq '.hasCompletedOnboarding = true' "${claude_state}" >"${tmp}"; then
        mv -f "${tmp}" "${claude_state}"
    else
        rm -f "${tmp}"
    fi
fi

# --- Session facts for the agent ------------------------------------------------
# /etc/claude-code/CLAUDE.md holds the general guidance. Write the values of this
# run into ~/work/CLAUDE.md, which Claude Code loads when started in
# ~/work or in a clone below it, so the agent knows the GitLab host and identity
# without having to look them up. A file that was not generated here is left alone.
workdir="${HOME}/work"
facts="${workdir}/CLAUDE.md"
marker='<!-- generated by entrypoint.sh -->'
if [ -d "${workdir}" ] && { [ ! -e "${facts}" ] || head -n1 "${facts}" | grep -qF -- "${marker}"; }; then
    {
        echo "${marker}"
        echo '# This session'
        echo
        echo "- GitLab host: \`${GITLAB_HOST:-gitlab.com}\` (https://${GITLAB_HOST:-gitlab.com})."
        if [ -n "${GITLAB_TOKEN:-}" ]; then
            echo '- `glab` and git over HTTPS are authenticated with `GITLAB_TOKEN`.'
        else
            echo '- No `GITLAB_TOKEN` is set: `glab` is not authenticated. Tell the user'
            echo '  instead of trying to log in.'
        fi
        [ -n "${name}" ] && echo "- Commits are authored as ${name}${email:+ <${email}>}."
        echo "- Working directory: \`${workdir}\`. Clone repositories here"
        echo '  with `glab repo clone <group>/<project>`; outside a clone, pass'
        echo '  `-R <group>/<project>` to `glab`.'
    } >"${facts}" 2>/dev/null || true
fi

exec "$@"
